
#变量练习

#1.创建变量
my_name = "Xufang"
my_age = 26
my_height = 1.72
is_student = False

#2.打印变量
print("My Information:")
print("Name:", my_name)
print("Age:", my_age)
print("Height:", my_height)
print("Student:", is_student)

#3. 变量重新赋值
my_age = 27
print()
print("After birthday")
print("New age:", my_age)

#4. 类型检查
print()
print("Data types:")
print("Name type:", type(my_name))
print("Age type:", type(my_age))
print("Height type:", type(my_height))
print("Student type:", type(is_student))
